export const getTitleByPerformance = (stats, quartersSurvived) => {
  const avg = (stats.people + stats.law + stats.integrity + stats.reform) / 4;
  
  if (quartersSurvived >= 16) {
    if (avg >= 75) return { title: "Công Bộc Xuất Sắc Toàn Diện", tier: "Huyền Thoại", color: "text-amber-400" };
    if (stats.reform >= 80) return { title: "Nhà Cải Cách Hành Chính Tiên Phong", tier: "Ưu Tú", color: "text-blue-400" };
    if (stats.law >= 80) return { title: "Ngọn Đèn Pháp Quyền Công Minh", tier: "Ưu Tú", color: "text-purple-400" };
    if (stats.people >= 80) return { title: "Cán Bộ Gần Dân - Thấu Lòng Dân", tier: "Ưu Tú", color: "text-emerald-400" };
    return { title: "Cán Bộ Bản Lĩnh - Hoàn Thành Nhiệm Kỳ", tier: "Khá Giỏi", color: "text-slate-200" };
  } else {
    if (quartersSurvived >= 12) return { title: "Cán Bộ Nhiệt Huyết Chưa Tròn Nhiệm Kỳ", tier: "Cần Rút Kinh Nghiệm", color: "text-yellow-500" };
    if (quartersSurvived >= 8) return { title: "Cán Bộ Còn Non Yếu Bản Lĩnh", tier: "Cần Rút Kinh Nghiệm", color: "text-orange-500" };
    return { title: "Chưa Đạt Chuẩn Công Bộc Của Dân", tier: "Chưa Đạt", color: "text-red-500" };
  }
};
